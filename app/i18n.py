PRESET_LABELS = {
    "Schule (Standard)": "preset_school",
    "Ferien": "preset_holiday",
    "Komplett gesperrt": "preset_locked",
}


def normalize_lang(code: str | None) -> str:
    if code and code.lower().startswith("en"):
        return "en"
    return "de"


def t(lang: str, key: str, **kwargs) -> str:
    language = normalize_lang(lang)
    text = STRINGS.get(language, {}).get(key) or STRINGS["de"].get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text


def reason_label(lang: str, code: str) -> str:
    language = normalize_lang(lang)
    return REASONS.get(language, REASONS["de"]).get(code, code)


def weekday(lang: str, index: int) -> str:
    return WEEKDAYS[normalize_lang(lang)][index]


def preset_label(lang: str, name: str) -> str:
    key = PRESET_LABELS.get(name)
    return t(lang, key) if key else name
